#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source_dir="$script_dir/fallback"
install_prefix="${HOME}/.local"
native_hint="${CODEX_FALLBACK_NATIVE:-}"
optional=false
configure_shell=true

while [[ $# -gt 0 ]]; do
  case "$1" in
    --prefix) install_prefix="${2:?--prefix requires a directory}"; shift 2 ;;
    --native) native_hint="${2:?--native requires a executable path}"; shift 2 ;;
    --if-available) optional=true; shift ;;
    --no-shell) configure_shell=false; shift ;;
    -h|--help)
      printf 'Usage: %s [--if-available] [--no-shell] [--prefix DIR] [--native EXECUTABLE]\n' "$0"
      exit 0 ;;
    *) printf 'Unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
done

export PATH="${HOME}/.local/bin:$PATH"
unavailable() {
  printf '[codex-fallback] %s\n' "$1" >&2
  if "$optional"; then exit 0; else exit 1; fi
}
command -v node >/dev/null 2>&1 || unavailable 'Node.js is missing; install Node.js 20+ first.'
command -v npm >/dev/null 2>&1 || unavailable 'npm is missing; install it first.'
node -e 'process.exit(Number(process.versions.node.split(".")[0]) >= 20 ? 0 : 1)' || unavailable 'Node.js 20+ is required.'

mkdir -p "$install_prefix"
install_prefix="$(cd "$install_prefix" && pwd)"
runtime_dir="$install_prefix/share/codex-fallback"
bin_dir="$install_prefix/bin"

native_candidates=()
[[ -z "$native_hint" ]] || native_candidates+=("$native_hint")
[[ ! -f "$runtime_dir/.native-codex" ]] || native_candidates+=("$(cat "$runtime_dir/.native-codex")")
native_candidates+=("$install_prefix/lib/node_modules/@openai/codex/bin/codex.js")
if npm_root="$(npm root -g 2>/dev/null)"; then
  native_candidates+=("$npm_root/@openai/codex/bin/codex.js")
fi
if native_command="$(type -P codex 2>/dev/null)"; then native_candidates+=("$native_command"); fi

native_path="$(node --input-type=module - "${native_candidates[@]}" <<'JS'
import { accessSync, constants, readFileSync, realpathSync } from 'node:fs';
import { basename } from 'node:path';
for (const candidate of process.argv.slice(2)) {
  try {
    const resolved = realpathSync(candidate);
    if (['codex-fallback', 'codex-fallback.mjs', 'codex-native'].includes(basename(resolved))) continue;
    accessSync(resolved, constants.X_OK);
    const prefix = readFileSync(resolved).subarray(0, 2048).toString();
    if (prefix.startsWith('#!') && /codex-fallback\.mjs/.test(prefix)) continue;
    console.log(resolved); break;
  } catch {}
}
JS
)"
[[ -n "$native_path" ]] || unavailable 'Native Codex CLI was not found; install @openai/codex first.'

mkdir -p "$runtime_dir" "$bin_dir"
for source_file in codex-fallback.mjs monitor.mjs routing.mjs native.mjs codex-fallback.test.mjs package.json package-lock.json README.md; do
  install -m 644 "$source_dir/$source_file" "$runtime_dir/$source_file"
done
printf '%s\n' "$native_path" > "$runtime_dir/.native-codex"
chmod 600 "$runtime_dir/.native-codex"

if ! node -e 'const p=require(process.argv[1]+"/node_modules/ws/package.json");process.exit(p.version==="8.18.3"?0:1)' "$runtime_dir" 2>/dev/null; then
  npm ci --prefix "$runtime_dir" --omit=dev --ignore-scripts --no-audit --no-fund
fi

install_launcher() {
  local name="$1" temporary="$bin_dir/.${1}.dotfiles-$$" destination="$bin_dir/$1"
  cat > "$temporary"
  chmod 755 "$temporary"
  if [[ -e "$destination" || -L "$destination" ]]; then
    if ! cmp -s "$temporary" "$destination"; then
      mkdir -p "$runtime_dir/backups"
      cp -P "$destination" "$runtime_dir/backups/${name}.$(date +%Y%m%d%H%M%S).$$"
    fi
  fi
  mv -f "$temporary" "$destination"
}

{
  printf '#!/usr/bin/env bash\n# Managed by dotfiles/codex/install-fallback.sh\n'
  printf 'exec node %q "$@"\n' "$runtime_dir/codex-fallback.mjs"
} | install_launcher codex-fallback
{
  printf '#!/usr/bin/env bash\n# Managed by dotfiles/codex/install-fallback.sh\n'
  printf 'exec %q "$@"\n' "$native_path"
} | install_launcher codex-native
for account in codex-personal codex2; do
  install_launcher "$account" < "$script_dir/$account"
done
# Replace npm's entry symlink, never the npm package it points at.
if [[ -e "$bin_dir/codex" || -L "$bin_dir/codex" ]]; then
  if [[ ! -L "$bin_dir/codex" ]] || [[ "$(readlink "$bin_dir/codex")" != "$bin_dir/codex-fallback" ]]; then
    mkdir -p "$runtime_dir/backups"
    cp -P "$bin_dir/codex" "$runtime_dir/backups/codex.$(date +%Y%m%d%H%M%S).$$"
  fi
fi
ln -s "$bin_dir/codex-fallback" "$bin_dir/.codex.dotfiles-$$"
mv -f "$bin_dir/.codex.dotfiles-$$" "$bin_dir/codex"

{
  printf '# Generated by dotfiles/codex/install-fallback.sh; works in Bash and Zsh.\n'
  printf 'if [ -x %q ]; then\n' "$bin_dir/codex-fallback"
  printf '  function codex { %q "$@"; }\nfi\n' "$bin_dir/codex-fallback"
} > "$runtime_dir/shell.sh"

if "$configure_shell"; then
  node --input-type=module - "$runtime_dir" "$HOME" <<'JS'
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const [runtime, home] = process.argv.slice(2);
const portable = runtime === join(home, '.local/share/codex-fallback');
const source = portable ? '"$HOME/.local/share/codex-fallback/shell.sh"' : `'${runtime.replaceAll("'", "'\\''")}/shell.sh'`;
const begin = '# >>> codex-fallback dotfiles >>>';
const end = '# <<< codex-fallback dotfiles <<<';
const block = `${begin}\nif [ -r ${source} ]; then\n  . ${source}\nfi\n${end}\n`;
for (const name of ['.bashrc', '.zshrc']) {
  const path = join(home, name);
  let existing;
  try { existing = readFileSync(path, 'utf8'); } catch { existing = ''; }
  const pattern = /# >>> codex-fallback dotfiles >>>[\s\S]*?# <<< codex-fallback dotfiles <<<\n?/;
  const updated = pattern.test(existing) ? existing.replace(pattern, block) : `${existing}${existing.endsWith('\n') || !existing ? '' : '\n'}\n${block}`;
  if (updated !== existing) writeFileSync(path, updated);
}
JS
fi
printf '[codex-fallback] Installed codex and codex-personal routing at %s\n' "$runtime_dir"
